export type StorageProvider = 's3' | 'local';

export interface PutObjectInput {
  key: string;
  body: Buffer;
  contentType: string;
  /** Hex SHA-256 of `body`. Drivers make the backend verify it so corrupted uploads are rejected. */
  sha256Hex: string;
  cacheControl?: string;
}

export interface ObjectInfo {
  size: number;
}

/** Low-level object storage. Business rules (allowed types, sizes, key layout) live in StorageService. */
export interface StorageDriver {
  readonly provider: StorageProvider;
  putObject(input: PutObjectInput): Promise<void>;
  /** Returns null when the object does not exist. */
  headObject(key: string): Promise<ObjectInfo | null>;
  getSignedReadUrl(key: string, expiresInSeconds: number): Promise<string>;
}

export const STORAGE_DRIVER = Symbol('STORAGE_DRIVER');

/** Object keys are generated by the app (`music/<id>.mp3`); anything else is rejected. */
export const OBJECT_KEY_PATTERN = /^[a-z0-9]+(?:\/[a-z0-9-]+)*\/[a-z0-9-]+\.[a-z0-9]+$/;
